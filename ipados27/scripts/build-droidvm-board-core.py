#!/usr/bin/env python3
"""The board's own part of the iPadOS 27 / macOS 27 kernel that is not a device driver: the droidvm-monitor worker and the
board's late probe hook (native_touch_probe, generated as DroidVMMonitor27.c), the calendar clock (DroidVMClock.c), the launch
policy (DroidVMLaunchPolicy.c), the built-in boot arguments (DroidVMBootArgs27.c), the host's file mailbox (DroidVMFileExport.c),
the page description (DroidVMPageInfo.c), the board support code the drivers and the monitor share (DroidVMBoardSupport27.cpp,
generated) and the kernel's side of the late probe when the display is a kext (DroidVMLateProbe.c).

iPadOS: build-droidvm-legacy-display.py archives these with the display (objects.json here). macOS, whose display, GPU, input
and key store are not this board's built-in drivers: the kernel's display archive (build/native-legacy-display/
libNativeLegacyDisplay.late.a, which XNU_NATIVE_LEGACY_DISPLAY links and whose late probe bsd_autoconf calls) holds these and
build-droidvm-devices.py's objects alone, with DroidVMLateProbe.c as the late probe.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import droidvm_kexts  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/droidvm-board-core'
OUT.mkdir(parents=True, exist_ok=True)
MACOS = os.environ.get('UNIXNU_XNU_TARGET') == 'macosx'
r = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json').read_text().strip().rstrip(','))


def run(cmd, **kw):
    return subprocess.check_output([str(x) for x in cmd], timeout=600, **kw)


def compile_cpp(src, dst, extra=()):
    cmd, args, i = [], r['arguments'], 0
    while i < len(args):
        value = args[i]
        if value == r['file']:
            cmd.append(str(src))
        elif value == '-o':
            cmd += ['-o', str(dst)]
            i += 1
        elif value in ('-MF', '-MT', '-MJ'):
            i += 1
        elif value == '-Xclang' and args[i + 1].startswith('-W'):
            i += 1
        elif not value.startswith('-W'):
            cmd.append(value)
        i += 1
    cmd += ['-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-Wno-unnecessary-virtual-specifier', '-Wno-c99-designator',
            '-Wno-reorder-init-list', '-Wno-deprecated-enum-enum-conversion', '-I', str(ROOT / '.cache/xnu-work/osfmk'), *extra]
    run(cmd, cwd=r['directory'])


def compile_c(src, dst, recipe='osfmk/DEVELOPMENT/startup.o.json', extra=()):
    """A C board core with the flags of one kernel C file (osfmk for the cores, bsd for the VFS readers)."""
    rc = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837' / recipe).read_text().strip().rstrip(','))
    cmd, args, i = [], rc['arguments'], 0
    while i < len(args):
        value = args[i]
        if value == rc['file']:
            cmd.append(str(src))
        elif value in ('-o', '-MF', '-MT', '-MJ'):
            if value == '-o':
                cmd += ['-o', str(dst)]
            i += 1
        elif value == '-Xclang' and args[i + 1].startswith('-W'):
            i += 1
        elif not value.startswith('-W'):
            cmd.append(value)
        i += 1
    cmd += ['-Wall', '-Wextra', '-Werror', '-mgeneral-regs-only', '-I', str(ROOT / '.cache/xnu-work/osfmk'), '-I', str(ROOT / 'kits/droidvm'),
            *extra]
    run(cmd, cwd=rc['directory'])


# The key store and the HID devices: built in on iPadOS unless they are kexts; never this board's built-in drivers on macOS.
input_kext = MACOS or 'NativeHidInput' in droidvm_kexts.builtin_left_out()
keystore_kext = MACOS or 'NativeKeyStoreEvents' in droidvm_kexts.builtin_left_out()
kext_flags = (*(('-DDROIDVM_KEXT_INPUT=1',) if input_kext else ()), *(('-DDROIDVM_KEXT_KEYSTORE=1',) if keystore_kext else ()))
board_support = OUT / 'DroidVMBoardSupport27.cpp'
board_support.write_text('''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Generated by build-droidvm-legacy-display.py: the board's part of the support code, which stays in the kernel when the display
// and the GPU are a kext (the display's is LegacyDisplaySupport27.cpp).
#include <IOKit/IOService.h>
#include <IOKit/IORegistryEntry.h>
// The board diagnostic page is not drawn on iPadOS 27: the keystore service's and the Data store's extension rows go nowhere.
extern "C" {char boot_progress_ext[8][48];}
// The board hooks the shared probe calls (as the iPadOS 17 board's DroidVMStubs.c defines them; sheng_gpu_power_probe is
// DroidVMGpu.cpp's, native_hid_input_probe HidInputProbe.cpp's, native_touch_probe -- the late probe's hook after bsd_autoconf --
// DroidVMMonitor27.c's): no cpufreq probe.
extern "C" void sheng_cpufreq_probe(void) {}
// The services the registry is busy on (a waitQuiet that never returns: configd's InterfaceNamer names an interface only once
// IOKit is quiet), refreshed by the monitor worker for the rig: "<busy> <class> <name>" lines, the deepest busy entries first.
extern "C" {char droidvm_busy_services[1536];volatile uint32_t droidvm_busy_count,droidvm_root_busy,droidvm_busy_scans;}
extern "C" void droidvm_busy_scan(void) {
    IOService *root=IOService::getServiceRoot();
    droidvm_busy_scans=droidvm_busy_scans+1;
    droidvm_root_busy=root?root->getBusyState():0;
    if(!droidvm_root_busy){droidvm_busy_count=0;droidvm_busy_services[0]=0;return;}
    IORegistryIterator *it=IORegistryIterator::iterateOver(gIOServicePlane,kIORegistryIterateRecursively);
    if(!it)return;
    char text[sizeof(droidvm_busy_services)];size_t used=0;uint32_t count=0;text[0]=0;
    while(IORegistryEntry *entry=it->getNextObject()) {
        IOService *service=OSDynamicCast(IOService,entry);
        if(!service || !service->getBusyState())continue;
        // only a busy entry whose children are all idle: the one actually holding the busy count
        bool childBusy=false;
        if(OSIterator *children=service->getChildIterator(gIOServicePlane)) {
            while(OSObject *child=children->getNextObject()) {
                IOService *c=OSDynamicCast(IOService,child);
                if(c && c->getBusyState()){childBusy=true;break;}
            }
            children->release();
        }
        if(childBusy)continue;
        ++count;
        int n=snprintf(text+used,sizeof(text)-used,"%u %s %s\\n",(unsigned)service->getBusyState(),
                       service->getMetaClass()->getClassName(),service->getName());
        if(n>0 && used+(size_t)n<sizeof(text))used+=(size_t)n;
    }
    it->release();
    memcpy(droidvm_busy_services,text,sizeof(text));droidvm_busy_count=count;
}
''')
compile_cpp(board_support, OUT / 'DroidVMBoardSupport27.o')

# The host's file mailbox (kits/droidvm/DroidVMFileExport.c, tools/rig export.py and crashes.py; a 4 MiB buffer allocated at the
# first poll, as the native __DATA must fit the original kernel's slot of the fileset before the first kext's data), answered
# every 100 ms by a worker that native_touch_probe starts with droidvm-monitor=<ms>, as the iPadOS 17 board's DroidVMStubs.c
# does; native_touch_probe also sets the calendar clock (DroidVMClock.c), starts the virtio-input devices (DroidVMVirtioInput.c,
# build-droidvm-hid-input.py), the network, sound, media and virtio-console devices, the battery and the vCPUs' performance
# requests to the host (DroidVMCpufreq.c; build-droidvm-devices.py), and holds the touch globals the input devices publish (without the iPadOS
# 17 board's process and trace probes).
monitor = OUT / 'DroidVMMonitor27.c'
monitor_text = ('''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Generated by build-droidvm-legacy-display.py: the droidvm-monitor worker of the iPadOS 27 board.
#include <stdint.h>
#include <kern/thread.h>
#include <pexpert/pexpert.h>
extern void IOSleep(unsigned milliseconds);
extern void droidvm_export_poll(void);
extern void droidvm_input_start(void);
extern void droidvm_net_start(void);
extern void droidvm_snd_start(void);
extern void droidvm_media_start(void);
extern void droidvm_console_start(void);
extern int droidvm_battery_attach(void);
extern int droidvm_software_aes_attach(void);
extern int droidvm_vt_paravirt_attach(void);
extern void droidvm_cpufreq_attach(void);
extern void droidvm_sched_trace_attach(void);
extern void droidvm_rtc_set_calendar(void);
extern void droidvm_fix_ownervisor_bootstrap(void);
extern void droidvm_busy_scan(void);
volatile uint32_t droidvm_monitor_passes;
// The touch frame DroidVMVirtioInput.c publishes for NativeHidInput, as DroidVMStubs.c holds it.
#define NATIVE_TOUCH_SLOTS 12
volatile uint32_t native_touch_seq;
volatile uint32_t native_touch_count;
volatile uint32_t native_touch_hid_reports;
volatile int native_touch_xs[NATIVE_TOUCH_SLOTS], native_touch_ys[NATIVE_TOUCH_SLOTS], native_touch_ids[NATIVE_TOUCH_SLOTS];
// NativeHidInput hands its button sink to sheng's ButtonProbe; this board has no buttons to report.
void native_buttons_set_sink(void (*sink)(void *, uint32_t), void *context) {(void)sink;(void)context;}
static void droidvm_monitor(void *parameter, wait_result_t result) {
    (void)parameter; (void)result;
    for (;;) {
        droidvm_export_poll();
        // ownervisor gets launchd's bootstrap port once launchd is up (DroidVMLaunchPolicy.c); a no-op once it took, or without it.
        droidvm_fix_ownervisor_bootstrap();
        if (droidvm_monitor_passes % 50 == 0) droidvm_busy_scan();   // every 5 s
        droidvm_monitor_passes = droidvm_monitor_passes + 1;
        IOSleep(100);
    }
}
void native_touch_probe(void) {
    unsigned interval = 0;
    thread_t thread;
    // The calendar from crosvm's PL030 (DroidVMClock.c), before launchd: the iPadOS 17 board sets it from its launch policy hook.
    droidvm_rtc_set_calendar();
    // the IOAESAccelerator AppleImage4 waits for on the defaults node (DroidVMSoftwareAES.cpp), first: until it is up an IOKit
    // configuration thread waits and the registry is never quiet
    droidvm_software_aes_attach();
    droidvm_input_start();
    droidvm_net_start();
    droidvm_snd_start();
    droidvm_media_start();
    droidvm_console_start();
    droidvm_vt_paravirt_attach();
    droidvm_battery_attach();
    droidvm_cpufreq_attach();
    droidvm_sched_trace_attach();
    if (!PE_parse_boot_argn("droidvm-monitor", &interval, sizeof(interval)) || !interval)
        return;
    if (kernel_thread_start(droidvm_monitor, NULL, &thread) == KERN_SUCCESS)
        thread_deallocate(thread);
}
''')
# A driver that ships as a kext of the collection (ipados27/kexts) is started by its kext's starter, not by this probe: its
# attach function is neither declared nor called here (it is not in the kernel).
# macOS: every device of the board is a kext of the macOS collection (or not there yet); the late probe keeps the clock, the trace
# and the monitor.
DEVICE_ATTACHES = {'droidvm_software_aes_attach', 'droidvm_input_start', 'droidvm_net_start', 'droidvm_snd_start', 'droidvm_media_start',
                   'droidvm_console_start', 'droidvm_vt_paravirt_attach', 'droidvm_battery_attach', 'droidvm_cpufreq_attach'}
for attach in sorted(DEVICE_ATTACHES if MACOS else droidvm_kexts.attach_left_out()):
    for line in (f'extern int {attach}(void);\n', f'extern void {attach}(void);\n', f'    {attach}();\n'):
        monitor_text = monitor_text.replace(line, '')
    if attach in monitor_text:
        raise SystemExit(f'{attach}: still named by the late probe')
monitor.write_text(monitor_text)
compile_c(monitor, OUT / 'DroidVMMonitor27.o')
clock_source = ROOT / 'kits/droidvm/DroidVMClock.c'
compile_c(clock_source, OUT / 'DroidVMClock.o', 'bsd/DEVELOPMENT/kern_exec.o.json')
# The launch policy hook before launchd (XNU_BOARD_LAUNCH_POLICY: launchd overrides, the plugin's GPU client list, lsd's first-boot
# mark, the App cryptex view, the owner service manager) and the board's built-in boot arguments, as on iPadOS 17.
policy_source = ROOT / 'kits/droidvm/DroidVMLaunchPolicy.c'
compile_c(policy_source, OUT / 'DroidVMLaunchPolicy.o', 'bsd/DEVELOPMENT/kern_exec.o.json')
# The built-in boot arguments of the OS the kernel serves.
bootargs_source = ROOT / 'kits/droidvm' / ('DroidVMBootArgsMacOS27.c' if MACOS else 'DroidVMBootArgs27.c')
compile_c(bootargs_source, OUT / 'DroidVMBootArgs27.o', 'bsd/DEVELOPMENT/kern_exec.o.json')
export_source = ROOT / 'kits/droidvm/DroidVMFileExport.c'
compile_c(export_source, OUT / 'DroidVMFileExport.o', 'bsd/DEVELOPMENT/kern_exec.o.json',
          ('-DDROIDVM_EXPORT_DYNAMIC=1', '-DDROIDVM_EXPORT_BYTES=(4u<<20)'))
# The mailbox's description of one vm_page (kind 8), with the VM's own flags: its object, pager and file.
page_info_source = ROOT / 'kits/droidvm/DroidVMPageInfo.c'
compile_c(page_info_source, OUT / 'DroidVMPageInfo.o', 'osfmk/DEVELOPMENT/vm_dyld_pager.o.json')
late_probe_source = ROOT / 'kits/droidvm/DroidVMLateProbe.c'
compile_c(late_probe_source, OUT / 'DroidVMLateProbe.o', extra=kext_flags)
objects = [OUT / name for name in ('DroidVMBoardSupport27.o', 'DroidVMMonitor27.o', 'DroidVMClock.o', 'DroidVMLaunchPolicy.o',
                                   'DroidVMBootArgs27.o', 'DroidVMFileExport.o', 'DroidVMPageInfo.o')]
sources = [clock_source, policy_source, bootargs_source, export_source, page_info_source, late_probe_source]
(OUT / 'objects.json').write_text(json.dumps(dict(objects=[str(p.relative_to(ROOT)) for p in objects],
                                                  late_probe=str((OUT / 'DroidVMLateProbe.o').relative_to(ROOT)),
                                                  sources=[str(p.relative_to(ROOT)) for p in sources]), indent=2) + '\n')
if MACOS:
    device_objects = [ROOT / p for p in json.loads((ROOT / 'build/droidvm-devices/objects.json').read_text())]
    display = ROOT / 'build/native-legacy-display'
    display.mkdir(parents=True, exist_ok=True)
    archive = display / 'libNativeLegacyDisplay.late.a'
    archive.unlink(missing_ok=True)
    run(['xcrun', 'ar', 'rcs', archive, OUT / 'DroidVMLateProbe.o', *objects, *device_objects])
    # what the kernel build checks before it links the archive (build-xnu-4k-baseline.sh): the archive and its sources, unchanged
    device_sources = [ROOT / p for p in json.loads((ROOT / 'build/droidvm-devices/sources.json').read_text())]
    digest = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()  # noqa: E731
    (display / 'build-report.json').write_text(json.dumps(dict(
        archive_sha256=digest(archive), source_sha256={str(p.relative_to(ROOT)): digest(p) for p in [*sources, *device_sources]},
        board_core_only=True), indent=2) + '\n')
    print(f'board core (macOS): {archive}')
else:
    print(f'board core: {len(objects)} objects')
